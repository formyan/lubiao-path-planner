  function renderNode(n, index) {
    const iconKey = NODE_ICONS[n.type] || "flag";
    const detailHtml = n.detail && n.detail.length
      ? '<div class="node-detail" id="nd-' + index + '">' + n.detail.map(d => {
          const items = d.items.map(it =>
            "<li" + (it.key ? ' class="is-key"' : "") + ">" + escapeHtml(it.t) + "</li>"
          ).join("");
          return '<div class="detail-block"><div class="detail-label">' + svg(ICONS[d.icon] || ICONS.check) + "<span>" + d.label + "</span></div><ul class=\"detail-list\">" + items + "</ul></div>";
        }).join("") + "</div>"
      : "";

    return (
      '<div class="node ' + n.type + '">' +
        '<div class="node-rail"><span class="node-dot"></span></div>' +
        '<div class="node-main">' +
          '<button type="button" class="node-card' + (n.detail && n.detail.length ? "" : " no-detail") + '" aria-expanded="false">' +
            '<span class="node-icon">' + svg(ICONS[iconKey]) + "</span>" +
            '<span class="node-body">' +
              '<span class="node-title-row"><span class="node-title"></span>' +
              (n.time ? '<span class="node-time"></span>' : "") + "</span>" +
              (n.summary ? '<span class="node-summary"></span>' : "") +
            "</span>" +
            (n.detail && n.detail.length
              ? '<span class="node-chevron">' + svg('<path d="M6 9l6 6 6-6"/>') + "</span>"
              : "") +
          "</button>" +
          detailHtml +
        "</div>" +
      "</div>" +
      '<div class="node-connector" aria-hidden="true"></div>'
    );
  }

  function escapeHtml(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  function fillNodeText(root, n) {
    $(".node-title", root).textContent = n.title;
    if (n.time) $(".node-time", root).textContent = n.time;
    if (n.summary) $(".node-summary", root).textContent = n.summary;
  }

  function renderPathPanel(path, index) {
    const panel = document.createElement("section");
    panel.className = "path-panel";
    panel.setAttribute("role", "tabpanel");
    panel.id = "panel-" + index;

    const diffClass = path.meta.difficulty === "高" ? "diff-high" : path.meta.difficulty === "中" ? "diff-mid" : "diff-low";

    panel.innerHTML =
      '<div class="path-intro">' +
        "<h3>" + escapeHtml(path.title) + (path.tag ? ' <span class="tab-tag">' + escapeHtml(path.tag) + "</span>" : "") + "</h3>" +
        "<p>" + escapeHtml(path.intro) + "</p>" +
        '<div class="meta-chips">' +
          '<span class="meta-chip ' + diffClass + '">难度：<b>' + escapeHtml(path.meta.difficulty) + "</b></span>" +
          '<span class="meta-chip">总时长：<b>' + escapeHtml(path.meta.duration) + "</b></span>" +
          '<span class="meta-chip">预估花费：<b>' + escapeHtml(path.meta.cost) + "</b></span>" +
          '<span class="meta-chip">成功率：<b>' + escapeHtml(path.meta.success) + "</b></span>" +
          '<span class="meta-chip">适合人群：<b>' + escapeHtml(path.meta.suitable) + "</b></span>" +
        "</div>" +
      "</div>" +
      '<div class="flow" aria-label="路径流程图"></div>';

    const flow = $(".flow", panel);
    const nodes = path.nodes.map((n, i) => {
      const html = renderNode(n, index + "-" + i);
      return i < path.nodes.length - 1 ? html : html.replace(/<div class="node-connector" aria-hidden="true"><\/div>$/, "");
    }).join("");
    flow.innerHTML = nodes;
    $$(".node", flow).forEach((el, i) => fillNodeText(el, path.nodes[i]));
    return panel;
  }

